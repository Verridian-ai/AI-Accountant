import { pgTable, text, integer, boolean, doublePrecision } from 'drizzle-orm/pg-core';
import { users } from './core.js';
import { accounts, statements } from './banking.js';
import { transactions } from './transactions.js';

// IMPORTANT — CURRENT_TIMESTAMP in PostgreSQL:
// The wrapPgDb() proxy stores the literal string 'CURRENT_TIMESTAMP' in PostgreSQL
// instead of evaluating it. All inserts MUST set timestamp fields explicitly:
//   createdAt: new Date().toISOString()   (see repositories/*.ts)

// ============================================================================
// PARSER METRICS & FEEDBACK
// ============================================================================

export const parserMetrics = pgTable('parser_metrics', {
  id: text('id').primaryKey(),
  statementId: text('statement_id').references(() => statements.id, { onDelete: 'cascade' }),
  bankName: text('bank_name').notNull(),
  parserUsed: text('parser_used').notNull(),
  extractionTimeMs: integer('extraction_time_ms'),
  transactionCount: integer('transaction_count'),
  confidenceScore: doublePrecision('confidence_score'),
  errorsCount: integer('errors_count').default(0),
  warningsCount: integer('warnings_count').default(0),
  usedVisionFallback: boolean('used_vision_fallback').default(false),
  bankId: text('bank_id'),
  totalDurationMs: integer('total_duration_ms'),
  parseErrorCount: integer('parse_error_count'),
  transactionsParsed: integer('transactions_parsed'),
  detectionConfidence: doublePrecision('detection_confidence'),
  highConfidenceCount: integer('high_confidence_count'),
  lowConfidenceCount: integer('low_confidence_count'),
  extractionMethod: text('extraction_method'),
  createdAt: text('created_at').notNull().default('CURRENT_TIMESTAMP'),
});

export const parserAccuracyAggregates = pgTable('parser_accuracy_aggregates', {
  id: text('id').primaryKey(),
  bankName: text('bank_name').notNull(),
  parserVersion: text('parser_version').notNull(),
  periodStart: text('period_start').notNull(),
  periodEnd: text('period_end').notNull(),
  totalStatements: integer('total_statements').notNull().default(0),
  successfulStatements: integer('successful_statements').notNull().default(0),
  avgConfidenceScore: doublePrecision('avg_confidence_score'),
  avgExtractionTimeMs: doublePrecision('avg_extraction_time_ms'),
  visionFallbackRate: doublePrecision('vision_fallback_rate'),
  bankId: text('bank_id'),
  periodType: text('period_type'),
  createdAt: text('created_at').notNull().default('CURRENT_TIMESTAMP'),
});

export const parserFeedback = pgTable('parser_feedback', {
  id: text('id').primaryKey(),
  userId: text('user_id')
    .notNull()
    .references(() => users.id, { onDelete: 'cascade' }),
  statementId: text('statement_id').references(() => statements.id, { onDelete: 'set null' }),
  transactionId: text('transaction_id').references(() => transactions.id, { onDelete: 'set null' }),
  feedbackType: text('feedback_type').notNull(),
  originalValue: text('original_value'),
  correctedValue: text('corrected_value'),
  fieldName: text('field_name'),
  notes: text('notes'),
  aiConfidence: text('ai_confidence'),
  userNotes: text('user_notes'),
  status: text('status').notNull().default('pending'),
  bankId: text('bank_id'),
  reviewedAt: text('reviewed_at'),
  reviewNotes: text('review_notes'),
  createdAt: text('created_at').notNull().default('CURRENT_TIMESTAMP'),
});

// ============================================================================
// FINANCIAL REPORTING & BUDGETING (Wave 13)
// ============================================================================

export const reportSnapshots = pgTable('report_snapshots', {
  id: text('id').primaryKey(),
  templateId: text('template_id').notNull(),
  userId: text('user_id')
    .notNull()
    .references(() => users.id, { onDelete: 'cascade' }),
  reportType: text('report_type').notNull(),
  periodStart: text('period_start').notNull(),
  periodEnd: text('period_end').notNull(),
  data: text('data').notNull(),
  comparisonData: text('comparison_data'),
  metadata: text('metadata'),
  generatedAt: text('generated_at').notNull().default('CURRENT_TIMESTAMP'),
});

export const budgets = pgTable('budgets', {
  id: text('id').primaryKey(),
  userId: text('user_id')
    .notNull()
    .references(() => users.id, { onDelete: 'cascade' }),
  accountId: text('account_id').references(() => accounts.id, { onDelete: 'set null' }),
  name: text('name').notNull(),
  budgetType: text('budget_type').notNull(),
  periodStart: text('period_start').notNull(),
  periodEnd: text('period_end').notNull(),
  totalAmount: integer('total_amount').notNull().default(0),
  status: text('status').notNull().default('draft'),
  autoGenerated: boolean('auto_generated').default(false),
  sourceMethod: text('source_method'),
  createdAt: text('created_at').notNull().default('CURRENT_TIMESTAMP'),
  updatedAt: text('updated_at').notNull().default('CURRENT_TIMESTAMP'),
});

export const budgetLines = pgTable('budget_lines', {
  id: text('id').primaryKey(),
  budgetId: text('budget_id')
    .notNull()
    .references(() => budgets.id, { onDelete: 'cascade' }),
  category: text('category').notNull(),
  subcategory: text('subcategory'),
  period: text('period').notNull(),
  budgetedAmount: integer('budgeted_amount').notNull(),
  notes: text('notes'),
  createdAt: text('created_at').notNull().default('CURRENT_TIMESTAMP'),
});

export const budgetVsActual = pgTable('budget_vs_actual', {
  id: text('id').primaryKey(),
  budgetLineId: text('budget_line_id')
    .notNull()
    .references(() => budgetLines.id, { onDelete: 'cascade' }),
  actualAmount: integer('actual_amount').notNull().default(0),
  varianceAmount: integer('variance_amount').notNull().default(0),
  variancePercent: doublePrecision('variance_percent').default(0),
  transactionCount: integer('transaction_count').default(0),
  lastCalculated: text('last_calculated').notNull().default('CURRENT_TIMESTAMP'),
});

export const forecastScenarios = pgTable('forecast_scenarios', {
  id: text('id').primaryKey(),
  userId: text('user_id')
    .notNull()
    .references(() => users.id, { onDelete: 'cascade' }),
  name: text('name').notNull(),
  scenarioType: text('scenario_type').notNull(),
  basePeriodStart: text('base_period_start').notNull(),
  basePeriodEnd: text('base_period_end').notNull(),
  forecastMonths: integer('forecast_months').notNull().default(12),
  assumptions: text('assumptions').notNull(),
  status: text('status').default('draft'),
  createdAt: text('created_at').notNull().default('CURRENT_TIMESTAMP'),
  updatedAt: text('updated_at').notNull().default('CURRENT_TIMESTAMP'),
});

export const forecastPeriods = pgTable('forecast_periods', {
  id: text('id').primaryKey(),
  scenarioId: text('scenario_id')
    .notNull()
    .references(() => forecastScenarios.id, { onDelete: 'cascade' }),
  period: text('period').notNull(),
  category: text('category').notNull(),
  forecastAmount: integer('forecast_amount').notNull(),
  confidenceLower: integer('confidence_lower'),
  confidenceUpper: integer('confidence_upper'),
  method: text('method').notNull(),
});

export const kpiMetrics = pgTable('kpi_metrics', {
  id: text('id').primaryKey(),
  userId: text('user_id')
    .notNull()
    .references(() => users.id, { onDelete: 'cascade' }),
  metricName: text('metric_name').notNull(),
  metricValue: integer('metric_value').notNull(),
  period: text('period').notNull(),
  targetValue: integer('target_value'),
  trendDirection: text('trend_direction'),
  previousValue: integer('previous_value'),
  calculatedAt: text('calculated_at').notNull().default('CURRENT_TIMESTAMP'),
});

// Type exports
export type ParserMetric = typeof parserMetrics.$inferSelect;
export type ParserAccuracyAggregate = typeof parserAccuracyAggregates.$inferSelect;
export type ParserFeedbackRecord = typeof parserFeedback.$inferSelect;
