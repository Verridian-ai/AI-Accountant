CREATE TABLE IF NOT EXISTS transactions (
    id TEXT PRIMARY KEY,
    date TEXT NOT NULL, -- ISO date YYYY-MM-DD
    description TEXT NOT NULL,
    amount INTEGER NOT NULL, -- Stored in cents. Positive = credit, negative = debit
    balance INTEGER, -- Running balance in cents
    category TEXT,
    gst_applicable BOOLEAN DEFAULT FALSE,
    ai_reasoning_notes TEXT,
    confidence_score REAL DEFAULT 1.0, -- 0.0 to 1.0
    is_edited BOOLEAN DEFAULT FALSE,
    is_transfer BOOLEAN DEFAULT FALSE,
    transfer_link_id TEXT,
    merchant_normalized TEXT,
    parent_transaction_id TEXT,
    statement_id TEXT REFERENCES statements(id) ON DELETE SET NULL,
    account_id TEXT REFERENCES accounts(id) ON DELETE SET NULL,
    user_id TEXT REFERENCES users(id) ON DELETE SET NULL
);

COMMENT ON TABLE transactions IS 'Individual financial transactions parsed from statements';
COMMENT ON COLUMN transactions.amount IS 'Amount in cents. Positive = credit/income, negative = debit/expense';
COMMENT ON COLUMN transactions.balance IS 'Running balance after this transaction, in cents';
COMMENT ON COLUMN transactions.gst_applicable IS 'Whether GST (10% Australian goods and services tax) applies';
COMMENT ON COLUMN transactions.confidence_score IS 'AI categorization confidence (1.0 = certain, 0.0 = guess)';
COMMENT ON COLUMN transactions.merchant_normalized IS 'Cleaned merchant name for grouping';

CREATE INDEX IF NOT EXISTS transactions_date_idx ON transactions(date);
CREATE INDEX IF NOT EXISTS transactions_user_id_idx ON transactions(user_id);
CREATE INDEX IF NOT EXISTS transactions_statement_id_idx ON transactions(statement_id);
CREATE INDEX IF NOT EXISTS transactions_category_idx ON transactions(category);
CREATE INDEX IF NOT EXISTS transactions_user_date_idx ON transactions(user_id, date);
CREATE INDEX IF NOT EXISTS transactions_account_id_idx ON transactions(account_id);
CREATE INDEX IF NOT EXISTS transactions_transfer_idx ON transactions(is_transfer, transfer_link_id);

-- Trigram index for fuzzy merchant search
CREATE INDEX IF NOT EXISTS transactions_merchant_trgm_idx ON transactions
    USING gin (merchant_normalized gin_trgm_ops);

CREATE TABLE IF NOT EXISTS transaction_history (
    id TEXT PRIMARY KEY,
    transaction_id TEXT REFERENCES transactions(id) ON DELETE SET NULL,
    change_type TEXT NOT NULL, -- 'create', 'update', 'delete', 'split', 'merge'
    old_data TEXT, -- JSON
    new_data TEXT, -- JSON
    timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE transaction_history IS 'Audit trail for transaction changes';

CREATE INDEX IF NOT EXISTS transaction_history_transaction_idx ON transaction_history(transaction_id);
CREATE INDEX IF NOT EXISTS transaction_history_timestamp_idx ON transaction_history(timestamp);

