-- =============================================================================
-- USERS & AUTHENTICATION
-- =============================================================================

CREATE TABLE IF NOT EXISTS users (
    id TEXT PRIMARY KEY,
    username TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT users_username_unique UNIQUE (username)
);

COMMENT ON TABLE users IS 'User accounts for the AI Accountant application';
COMMENT ON COLUMN users.id IS 'UUID generated by the application';
COMMENT ON COLUMN users.password_hash IS 'bcrypt hashed password';

CREATE TABLE IF NOT EXISTS user_settings (
    user_id TEXT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    model_parsing_text TEXT NOT NULL DEFAULT 'google/gemini-3-flash-preview',
    model_parsing_vision TEXT NOT NULL DEFAULT 'google/gemini-3-flash-preview',
    model_categorization TEXT NOT NULL DEFAULT 'google/gemini-3-flash-preview',
    model_chat TEXT NOT NULL DEFAULT 'google/gemini-3-flash-preview',
    model_embedding TEXT NOT NULL DEFAULT 'openai/text-embedding-3-large'
);

COMMENT ON TABLE user_settings IS 'AI model preferences per user';
COMMENT ON COLUMN user_settings.model_parsing_text IS 'Model used for text-based statement parsing';
COMMENT ON COLUMN user_settings.model_parsing_vision IS 'Model used for vision-based PDF parsing';

-- =============================================================================
-- ACCOUNTS
-- =============================================================================

CREATE TABLE IF NOT EXISTS accounts (
    id TEXT PRIMARY KEY,
    user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    account_number TEXT NOT NULL,
    account_number_hash TEXT NOT NULL,
    account_name TEXT NOT NULL,
    account_type TEXT NOT NULL, -- 'checking', 'savings', 'credit_card', 'loan'
    bank_name TEXT,
    current_balance INTEGER DEFAULT 0, -- Stored in cents (AUD)
    last_statement_date TEXT,
    interest_rate REAL, -- Decimal (e.g., 0.0525 for 5.25%)
    credit_limit INTEGER, -- Stored in cents (AUD)
    minimum_payment INTEGER, -- Stored in cents (AUD)
    payment_due_day INTEGER,
    linked_payment_account_id TEXT,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE accounts IS 'Bank accounts linked by users';
COMMENT ON COLUMN accounts.current_balance IS 'Balance in cents (Australian dollars). Positive = credit, negative = debit';
COMMENT ON COLUMN accounts.account_number_hash IS 'SHA-256 hash for duplicate detection without storing full number';
COMMENT ON COLUMN accounts.interest_rate IS 'Annual interest rate as decimal (0.0525 = 5.25%)';

CREATE INDEX IF NOT EXISTS accounts_user_id_idx ON accounts(user_id);
CREATE INDEX IF NOT EXISTS accounts_hash_idx ON accounts(account_number_hash);

CREATE TABLE IF NOT EXISTS account_balance_history (
    id TEXT PRIMARY KEY,
    account_id TEXT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    balance INTEGER NOT NULL, -- Stored in cents (AUD)
    balance_date TEXT NOT NULL, -- ISO date YYYY-MM-DD
    source TEXT NOT NULL, -- 'statement', 'manual', 'calculated'
    statement_id TEXT,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE account_balance_history IS 'Historical balance snapshots for reconciliation';
COMMENT ON COLUMN account_balance_history.balance IS 'Balance in cents at the specified date';

CREATE INDEX IF NOT EXISTS balance_history_account_date_idx ON account_balance_history(account_id, balance_date);

-- =============================================================================
-- STATEMENTS
-- =============================================================================

CREATE TABLE IF NOT EXISTS statements (
    id TEXT PRIMARY KEY,
    filename TEXT NOT NULL,
    hash TEXT NOT NULL,
    upload_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    parsing_status TEXT NOT NULL DEFAULT 'PENDING', -- 'PENDING', 'PROCESSING', 'COMPLETED', 'FAILED'
    ai_model_used TEXT,
    error_message TEXT,
    error_type TEXT,
    error_details TEXT, -- JSON for structured error info
    user_id TEXT REFERENCES users(id) ON DELETE SET NULL,
    period_start_date TEXT, -- ISO date YYYY-MM-DD
    period_end_date TEXT,   -- ISO date YYYY-MM-DD
    opening_balance INTEGER, -- Stored in cents (AUD)
    closing_balance INTEGER, -- Stored in cents (AUD)
    transaction_count INTEGER DEFAULT 0,
    is_complete BOOLEAN DEFAULT TRUE,
    validation_errors TEXT, -- JSON array of validation errors

    CONSTRAINT statements_hash_unique UNIQUE (hash)
);

COMMENT ON TABLE statements IS 'Uploaded bank statements (PDF, CSV, OFX, QIF)';
COMMENT ON COLUMN statements.hash IS 'SHA-256 hash for duplicate detection';
COMMENT ON COLUMN statements.opening_balance IS 'Opening balance from statement in cents';
COMMENT ON COLUMN statements.closing_balance IS 'Closing balance from statement in cents';

CREATE INDEX IF NOT EXISTS statements_user_id_idx ON statements(user_id);
CREATE INDEX IF NOT EXISTS statements_upload_date_idx ON statements(upload_date);
CREATE INDEX IF NOT EXISTS statements_user_date_idx ON statements(user_id, upload_date);
CREATE INDEX IF NOT EXISTS statements_period_idx ON statements(period_start_date, period_end_date);

-- Junction table for statements that contain multiple accounts
CREATE TABLE IF NOT EXISTS statement_accounts (
    statement_id TEXT PRIMARY KEY REFERENCES statements(id) ON DELETE CASCADE,
    account_id TEXT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE
);

COMMENT ON TABLE statement_accounts IS 'Links statements to accounts (for multi-account statements)';

-- Add foreign key for account_balance_history -> statements
ALTER TABLE account_balance_history
    ADD CONSTRAINT account_balance_history_statement_id_fk
    FOREIGN KEY (statement_id) REFERENCES statements(id) ON DELETE SET NULL;

-- =============================================================================
-- TRANSACTIONS
