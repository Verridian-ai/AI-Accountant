-- This migration creates the PostgreSQL schema for the AI Accountant fintech
-- application, previously running on SQLite.
--
-- Key Design Decisions:
-- - UUIDs stored as TEXT (application generates them, not database)
-- - Currency amounts stored as INTEGER (cents) to avoid floating-point errors
-- - All timestamps use TIMESTAMPTZ for timezone awareness
-- - Appropriate indexes for common query patterns
-- - Foreign key constraints with appropriate ON DELETE behavior
--
-- Run with: psql -d ai_accountant -f 0006_postgres_migration.sql
-- =============================================================================

