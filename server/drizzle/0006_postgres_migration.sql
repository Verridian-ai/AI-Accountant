-- Function to convert cents to dollars for display
CREATE OR REPLACE FUNCTION cents_to_dollars(cents INTEGER)
RETURNS NUMERIC(12,2) AS $$
BEGIN
    IF cents IS NULL THEN
        RETURN NULL;
    END IF;
    RETURN cents / 100.0;
END;
$$ LANGUAGE plpgsql IMMUTABLE;

COMMENT ON FUNCTION cents_to_dollars IS 'Convert cents (INTEGER) to dollars (NUMERIC) for display';

-- Function to convert dollars to cents for storage
CREATE OR REPLACE FUNCTION dollars_to_cents(dollars NUMERIC)
RETURNS INTEGER AS $$
BEGIN
    IF dollars IS NULL THEN
        RETURN NULL;
    END IF;
    RETURN ROUND(dollars * 100)::INTEGER;
END;
$$ LANGUAGE plpgsql IMMUTABLE;

COMMENT ON FUNCTION dollars_to_cents IS 'Convert dollars (NUMERIC) to cents (INTEGER) for storage';

-- Function to calculate GST amount (Australian 10%)
CREATE OR REPLACE FUNCTION calculate_gst(amount_cents INTEGER)
RETURNS INTEGER AS $$
BEGIN
    IF amount_cents IS NULL THEN
        RETURN NULL;
    END IF;
    -- GST = Amount / 11 (since GST-inclusive amount = base + 10% = base * 1.1)
    RETURN ROUND(amount_cents / 11.0)::INTEGER;
END;
$$ LANGUAGE plpgsql IMMUTABLE;

COMMENT ON FUNCTION calculate_gst IS 'Calculate GST component from a GST-inclusive amount in cents (Australian 10% GST)';

-- =============================================================================
-- UPDATED_AT TRIGGER
-- =============================================================================

CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Apply trigger to tables with updated_at column
DROP TRIGGER IF EXISTS update_users_updated_at ON users;
CREATE TRIGGER update_users_updated_at
    BEFORE UPDATE ON users
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

DROP TRIGGER IF EXISTS update_accounts_updated_at ON accounts;
CREATE TRIGGER update_accounts_updated_at
    BEFORE UPDATE ON accounts
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

DROP TRIGGER IF EXISTS update_debt_payoff_scenarios_updated_at ON debt_payoff_scenarios;
CREATE TRIGGER update_debt_payoff_scenarios_updated_at
    BEFORE UPDATE ON debt_payoff_scenarios
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

